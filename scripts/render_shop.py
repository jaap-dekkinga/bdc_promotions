#!/usr/bin/env python3
"""
Render the shop cards in index.html from data/products.json.

The cards live between the shop:start and shop:end markers inside the
shop grid. Everything between them is generated, so never edit it by hand:
change data/products.json and run this script.

A product is shown only when it has status "live", a "Be ___" phrase, a DC
fact and an image. Drafts (for example new products found by the Printful
sync) stay in the catalog but off the page until they're ready.
A product's "buy_url" (its Printful Quick Store link) becomes the card's
data-buy-url; main.js turns that into a "Shop this design" button. Without
one the button says "Notify me".

Usage:
  python scripts/render_shop.py           rewrite index.html
  python scripts/render_shop.py --check   exit 1 if index.html is out of date (CI)
"""
import argparse
import json
import re
import sys
from decimal import Decimal, InvalidOperation
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "products.json"
PAGE = ROOT / "index.html"
START = "<!-- shop:start (generated by scripts/render_shop.py from data/products.json; don't edit by hand) -->"
END = "<!-- shop:end -->"
SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")

CARD = """        <article class="product-card" data-slug="{slug}" data-name="{title}"{buy}>
          <div class="product-media"><img src="{image}" alt="{alt}" /></div>
          <div class="product-body">
            <p class="product-be"><span class="product-be-star">★</span> {be}</p>
            <div class="product-name">{name}</div>
            <div class="product-price">{price}</div>
            <p class="product-fact"><span class="product-fact-label">Did you know</span>{fact}</p>
            <a class="btn btn-outline btn-block shop-btn" href="#contact">Notify me</a>
          </div>
        </article>
"""


def text(value):
    return str(value).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def attr(value):
    return text(value).replace('"', "&quot;")


def money(price):
    """"30.00" -> "$30", "27.5" -> "$27.50"."""
    try:
        amount = Decimal(str(price))
    except InvalidOperation:
        raise ValueError(f"price is not a number: {price!r}")
    return f"${amount:.0f}" if amount == amount.to_integral() else f"${amount:.2f}"


def is_shown(p):
    return (p.get("status") == "live" and p.get("be") and p.get("dc_fact")
            and p.get("image") and (ROOT / p["image"]).is_file())


def cards(products):
    out = []
    for p in products:
        if not is_shown(p):
            continue
        if not SLUG.match(p.get("slug", "")):
            raise ValueError(f"bad slug {p.get('slug')!r}: use lowercase letters, digits and dashes")
        if not p["image"].startswith("assets/") or ".." in p["image"]:
            raise ValueError(f"{p['slug']}: image must be under assets/ (bedc.shop serves nothing else)")
        buy_url = (p.get("buy_url") or "").strip()
        if buy_url and not buy_url.startswith("https://"):
            raise ValueError(f"{p['slug']}: buy_url must be an https:// link (Jaap's real Printful link)")
        out.append(CARD.format(
            slug=p["slug"], title=attr(p["title"]), buy=f' data-buy-url="{attr(buy_url)}"' if buy_url else "",
            image=attr(p["image"]),
            alt=attr(p.get("alt") or p["title"]), be=text(p["be"]),
            name=text(p.get("name") or p["title"]), price=money(p["price"]),
            fact=text(p["dc_fact"])))
    return "\n".join(out)


def render(page, products):
    start, end = page.find(START), page.find(END)
    if start < 0 or end < start:
        raise ValueError("index.html is missing the shop:start / shop:end markers")
    head = page[:start + len(START)]
    tail = page[end:]
    return f"{head}\n{cards(products)}        {tail}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[1])
    ap.add_argument("--check", action="store_true", help="fail if index.html is out of date")
    args = ap.parse_args()
    products = json.loads(DATA.read_text(encoding="utf-8"))
    page = PAGE.read_text(encoding="utf-8")
    try:
        new = render(page, products)
    except ValueError as e:
        sys.exit(f"render_shop: {e}")
    shown = sum(1 for p in products if is_shown(p))
    if args.check:
        if new != page:
            sys.exit("index.html shop cards don't match data/products.json. "
                     "Run: python scripts/render_shop.py")
        print(f"OK: shop shows {shown} of {len(products)} products, in sync with data/products.json")
        return
    if new != page:
        PAGE.write_text(new, encoding="utf-8", newline="\n")
    print(f"Rendered {shown} of {len(products)} products into index.html")


if __name__ == "__main__":
    main()
